# Automated Document Organizer

import os
import shutil

print("=" * 60)
print("AUTOMATED DOCUMENT ORGANIZER")
print("=" * 60)

# Create a safe demo folder
base_folder = "DocumentOrganizer_Demo"
os.makedirs(base_folder, exist_ok=True)

# Create sample files automatically
sample_files = [
    "report.pdf",
    "notes.txt",
    "photo.jpg",
    "image.png",
    "video.mp4",
    "music.mp3",
    "archive.zip",
    "data.csv",
    "presentation.pptx"
]

for filename in sample_files:
    filepath = os.path.join(base_folder, filename)

    if not os.path.exists(filepath):
        with open(filepath, "w") as f:
            f.write("Sample file created by Python automation project.\n")

# Define file categories
categories = {
    "Documents": [".pdf", ".doc", ".docx", ".txt", ".ppt", ".pptx"],
    "Images": [".jpg", ".jpeg", ".png", ".gif", ".bmp"],
    "Videos": [".mp4", ".mkv", ".mov", ".avi"],
    "Audio": [".mp3", ".wav", ".aac"],
    "Archives": [".zip", ".rar", ".7z"],
    "Data": [".csv", ".xlsx", ".json", ".xml"]
}

# Organize files
moved_count = 0
skipped_count = 0

for filename in os.listdir(base_folder):
    source = os.path.join(base_folder, filename)

    # Skip folders
    if os.path.isdir(source):
        continue

    extension = os.path.splitext(filename)[1].lower()
    destination_category = "Others"

    # Identify category
    for category, extensions in categories.items():
        if extension in extensions:
            destination_category = category
            break

    destination_folder = os.path.join(
        base_folder, destination_category
    )

    os.makedirs(destination_folder, exist_ok=True)

    destination = os.path.join(destination_folder, filename)

    # Avoid overwriting duplicate files
    if os.path.exists(destination):
        print("Skipped duplicate:", filename)
        skipped_count += 1
        continue

    try:
        shutil.move(source, destination)
        print(f"Moved {filename} -> {destination_category}")
        moved_count += 1

    except (OSError, shutil.Error) as error:
        print(f"Error moving {filename}: {error}")

print("\n" + "=" * 60)
print("ORGANIZATION SUMMARY")
print("=" * 60)
print("Files moved:", moved_count)
print("Files skipped:", skipped_count)

print("\nFolders created:")

for folder in os.listdir(base_folder):
    path = os.path.join(base_folder, folder)

    if os.path.isdir(path):
        print("-", folder, ":", len(os.listdir(path)), "files")

print("\nFile organization completed successfully!")
print("Demo folder location:", os.path.abspath(base_folder))