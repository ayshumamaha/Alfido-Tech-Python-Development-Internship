# GitHub Repository Explorer

import requests

print("=" * 60)
print("GITHUB REPOSITORY EXPLORER")
print("=" * 60)

query = input("Enter repository search (e.g., python AI): ").strip()

if not query:
    query = "python"

url = "https://api.github.com/search/repositories"

params = {
    "q": query,
    "sort": "stars",
    "order": "desc",
    "per_page": 15
}

headers = {
    "Accept": "application/vnd.github+json"
}

try:
    print("\nConnecting to GitHub API...")

    response = requests.get(
        url,
        params=params,
        headers=headers,
        timeout=15
    )

    if response.status_code == 200:
        data = response.json()
        repositories = data.get("items", [])

        print("\nTotal matching repositories:", data.get("total_count", 0))

        if not repositories:
            print("No repositories found.")
        else:
            # Display results
            print("\nTOP REPOSITORIES")
            print("-" * 60)

            for i, repo in enumerate(repositories, start=1):
                print(f"\n{i}. {repo.get('full_name', 'Unknown')}")
                print("Description:", repo.get("description") or "No description")
                print("Language:", repo.get("language") or "Not specified")
                print("Stars:", repo.get("stargazers_count", 0))
                print("Forks:", repo.get("forks_count", 0))
                print("URL:", repo.get("html_url", ""))

            # Filter by language
            languages = sorted(set(
                repo["language"]
                for repo in repositories
                if repo.get("language")
            ))

            print("\nAvailable languages:")
            print(", ".join(languages) if languages else "None")

            selected_language = input(
                "\nFilter by language (press Enter to skip): "
            ).strip()

            if selected_language:
                filtered = [
                    repo for repo in repositories
                    if repo.get("language", "").lower()
                    == selected_language.lower()
                ]

                print(f"\nRepositories using {selected_language}:")
                print("-" * 60)

                if filtered:
                    for repo in filtered:
                        print(
                            repo["full_name"],
                            "| Stars:", repo["stargazers_count"],
                            "|", repo.get("html_url")
                        )
                else:
                    print("No repositories found for that language.")

            # Sort by stars
            sorted_repos = sorted(
                repositories,
                key=lambda repo: repo.get("stargazers_count", 0),
                reverse=True
            )

            print("\nTOP 5 REPOSITORIES BY STARS:")
            for repo in sorted_repos[:5]:
                print(
                    repo["full_name"],
                    "-",
                    repo["stargazers_count"],
                    "stars"
                )

    elif response.status_code == 403:
        print("GitHub API rate limit reached. Try again later.")

    elif response.status_code == 422:
        print("Invalid search query.")

    else:
        print("API Error:", response.status_code)
        print(response.text[:500])

except requests.exceptions.Timeout:
    print("Request timed out. Please try again.")

except requests.exceptions.ConnectionError:
    print("Connection error. Check your internet connection.")

except requests.exceptions.RequestException as error:
    print("Request failed:", error)

except ValueError:
    print("Could not process the JSON response.")

print("\nProgram finished.")