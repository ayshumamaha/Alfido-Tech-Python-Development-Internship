# Home page
@app.route("/")
def home():
    tasks = load_tasks()

    total = len(tasks)
    completed = sum(1 for task in tasks if task["completed"])
    pending = total - completed

    return render_template_string(
        HTML,
        tasks=tasks,
        total=total,
        pending=pending,
        completed=completed
    )

# Add assignment
@app.route("/add", methods=["POST"])
def add_task():
    tasks = load_tasks()

    task = {
        "id": str(uuid.uuid4()),
        "title": request.form.get("title", "").strip(),
        "subject": request.form.get("subject", "").strip(),
        "description": request.form.get("description", "").strip(),
        "due_date": request.form.get("due_date", ""),
        "completed": False
    }

    if task["title"] and task["subject"] and task["due_date"]:
        tasks.append(task)
        save_tasks(tasks)

    return redirect("/")

# Toggle completion
@app.route("/toggle/<task_id>", methods=["POST"])
def toggle_task(task_id):
    tasks = load_tasks()

    for task in tasks:
        if task["id"] == task_id:
            task["completed"] = not task["completed"]
            break

    save_tasks(tasks)
    return redirect("/")

# Edit assignment
@app.route("/edit/<task_id>", methods=["GET", "POST"])
def edit_task(task_id):
    tasks = load_tasks()

    task = next(
        (t for t in tasks if t["id"] == task_id),
        None
    )

    if task is None:
        return "Assignment not found", 404

    if request.method == "POST":
        task["title"] = request.form.get("title", "").strip()
        task["subject"] = request.form.get("subject", "").strip()
        task["description"] = request.form.get("description", "").strip()
        task["due_date"] = request.form.get("due_date", "")

        save_tasks(tasks)
        return redirect("/")

    return render_template_string(EDIT_HTML, task=task)

# Delete assignment
@app.route("/delete/<task_id>", methods=["POST"])
def delete_task(task_id):
    tasks = load_tasks()

    tasks = [
        task for task in tasks
        if task["id"] != task_id
    ]

    save_tasks(tasks)
    return redirect("/")

