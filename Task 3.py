import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("=" * 60)
print("RETAIL SALES & PRODUCT PERFORMANCE ANALYZER")
print("=" * 60)

# Create sample dataset automatically
np.random.seed(42)

products = ["Laptop", "Mouse", "Keyboard", "Monitor", "Headphones"]
categories = ["Electronics", "Accessories", "Electronics", "Electronics", "Accessories"]
prices = [55000, 800, 1500, 12000, 2500]

rows = []

for i in range(200):
    product_index = np.random.randint(0, len(products))

    rows.append({
        "Date": pd.Timestamp("2025-01-01")
                  + pd.Timedelta(days=np.random.randint(0, 365)),
        "Product": products[product_index],
        "Category": categories[product_index],
        "Quantity": np.random.randint(1, 10),
        "Price": prices[product_index]
    })

df = pd.DataFrame(rows)

# Save sample data
csv_file = "retail_sales_data.csv"
df.to_csv(csv_file, index=False)

print("\nSample dataset created:", csv_file)

# Load dataset
df = pd.read_csv(csv_file)

print("\nDATASET PREVIEW")
print(df.head())

print("\nDataset shape:", df.shape)

print("\nDATA TYPES")
print(df.dtypes)

print("\nMISSING VALUES")
print(df.isnull().sum())

# Clean data
df.dropna(inplace=True)

df["Date"] = pd.to_datetime(df["Date"], errors="coerce")
df["Quantity"] = pd.to_numeric(df["Quantity"], errors="coerce")
df["Price"] = pd.to_numeric(df["Price"], errors="coerce")

df.dropna(inplace=True)

df = df[df["Quantity"] > 0]
df = df[df["Price"] >= 0]

# Calculate revenue
df["Revenue"] = df["Quantity"] * df["Price"]

print("\nCLEANED DATA")
print(df.head())

# Overall summary
print("\nTOTAL SALES QUANTITY:", df["Quantity"].sum())
print("TOTAL REVENUE:", round(df["Revenue"].sum(), 2))
print("AVERAGE ORDER REVENUE:", round(df["Revenue"].mean(), 2))

# Product analysis
product_summary = df.groupby("Product").agg(
    Total_Quantity=("Quantity", "sum"),
    Total_Revenue=("Revenue", "sum")
).sort_values("Total_Revenue", ascending=False)

print("\nPRODUCT PERFORMANCE")
print(product_summary)

# Category analysis
category_summary = df.groupby("Category").agg(
    Total_Quantity=("Quantity", "sum"),
    Total_Revenue=("Revenue", "sum")
).sort_values("Total_Revenue", ascending=False)

print("\nCATEGORY PERFORMANCE")
print(category_summary)

# Monthly analysis
df["Month"] = df["Date"].dt.to_period("M").astype(str)

monthly_summary = df.groupby("Month")["Revenue"].sum()

print("\nMONTHLY REVENUE")
print(monthly_summary)

# Top products
top_products = product_summary.head(5)

print("\nTOP PRODUCTS")
print(top_products)

# Plot 1: Revenue by product
product_summary["Total_Revenue"].plot(
    kind="bar", figsize=(8, 5)
)

plt.title("Revenue by Product")
plt.ylabel("Revenue")
plt.xlabel("Product")
plt.xticks(rotation=30)
plt.tight_layout()
plt.show()

# Plot 2: Category revenue
category_summary["Total_Revenue"].plot(
    kind="pie", autopct="%1.1f%%", figsize=(7, 7)
)

plt.title("Category Revenue Distribution")
plt.ylabel("")
plt.tight_layout()
plt.show()

# Plot 3: Monthly revenue
monthly_summary.plot(
    kind="line", marker="o", figsize=(10, 5)
)

plt.title("Monthly Sales Revenue")
plt.xlabel("Month")
plt.ylabel("Revenue")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# Generate insights
best_product = product_summary["Total_Revenue"].idxmax()
best_category = category_summary["Total_Revenue"].idxmax()
best_month = monthly_summary.idxmax()

print("\n" + "=" * 60)
print("BUSINESS INSIGHTS")
print("=" * 60)

print("Best revenue-generating product:", best_product)
print("Best revenue-generating category:", best_category)
print("Highest revenue month:", best_month)
print("Total records analyzed:", len(df))
print("Total revenue:", round(df["Revenue"].sum(), 2))

print("\nAnalysis completed successfully!")